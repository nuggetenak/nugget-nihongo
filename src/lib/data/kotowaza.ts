/**
 * Return daily proverb deterministically based on epoch day
 */
export function getDailyKotowaza(): Kotowaza {
  const dayIndex = Math.floor(Date.now() / 86400000);
  return KOTOWAZA_COLLECTION[dayIndex % KOTOWAZA_COLLECTION.length];
}

/**
 * Get all available proverb categories
 */
export function getKotowazaCategories(): string[] {
  const cats = new Set<string>();
  for (const item of KOTOWAZA_COLLECTION) {
    cats.add(item.category);
  }
  return ['all', ...Array.from(cats)];
}

export const KOTOWAZA_LIST = KOTOWAZA_COLLECTION;
